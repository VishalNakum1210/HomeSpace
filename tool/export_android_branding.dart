const canvasColor = Color(0xFFFFFEFC);
const housePath =
    'M10,29 L32,10 L54,29 L54,55 Q54,60 49,60 L15,60 Q10,60 10,55 Z';
const roofPath = 'M7,28 L32,6 L57,28';
const eyes =
    'M21,35.5 A2.5,3.5 0,1 0,26,35.5 A2.5,3.5 0,1 0,21,35.5 Z '
    'M38,35.5 A2.5,3.5 0,1 0,43,35.5 A2.5,3.5 0,1 0,38,35.5 Z';
const smile = 'M26,44 Q32,52 38,44 Z';
const cheeks =
    'M14.5,43 A3.5,3.5 0,1 0,21.5,43 A3.5,3.5 0,1 0,14.5,43 Z '
    'M42.5,43 A3.5,3.5 0,1 0,49.5,43 A3.5,3.5 0,1 0,42.5,43 Z';

