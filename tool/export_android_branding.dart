String adaptive() => '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''';

Future<void> write(String path, String content) async {
  final file = File(path);
  await file.parent.create(recursive: true);
  await file.writeAsString(content);
}

void main() {
  testWidgets('Export house branding and verify launcher safe area', (
    tester,
  ) async {
    const capture = ValueKey('branding-capture');
    Future<ui.Image> render(Widget child, int pixels, double logical) async {
      await tester.pumpWidget(
        Directionality(
          textDirection: TextDirection.ltr,
          child: Center(
            child: RepaintBoundary(
              key: capture,
              child: SizedBox.square(dimension: logical, child: child),
            ),
          ),
        ),
      );
      await tester.pump();
      final boundary = tester.renderObject<RenderRepaintBoundary>(
        find.byKey(capture),
      );
      return (await tester.runAsync(
        () => boundary.toImage(pixelRatio: pixels / logical),
      ))!;
    }

    Future<void> png(ui.Image image, String path) async {
      await tester.runAsync(() async {
        final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
        final file = File(path);
        await file.parent.create(recursive: true);
        await file.writeAsBytes(bytes!.buffer.asUint8List());
      });
      image.dispose();
    }

    Widget legacy({bool round = false}) => DecoratedBox(
      decoration: BoxDecoration(
        color: canvasColor,
        borderRadius: BorderRadius.circular(round ? 32 : 14),
      ),
      child: const Stack(
        children: [
          Positioned(left: 8, top: 9.875, child: SpaceHouse(size: 48)),
        ],
      ),
    );

    for (final density in {
      'mdpi': 48,
      'hdpi': 72,
      'xhdpi': 96,
      'xxhdpi': 144,
      'xxxhdpi': 192,
    }.entries) {
      for (final round in [false, true]) {
        final image = await render(legacy(round: round), density.value, 64);
        expect(image.width, density.value);
        await png(
          image,
          '$res/mipmap-${density.key}/ic_launcher${round ? '_round' : ''}.png',
        );
      }
    }

    // Same placement as the native foreground. Check the mandatory safe circle.
    final foreground = await render(
      const Stack(
        children: [
          Positioned(left: 25.2, top: 27.45, child: SpaceHouse(size: 57.6)),
        ],
      ),
      432,
      108,
    );
    final pixels = (await tester.runAsync(() => foreground.toByteData()))!
        .buffer
        .asUint8List();
    for (var y = 0; y < 432; y++) {
      for (var x = 0; x < 432; x++) {
        if (pixels[(y * 432 + x) * 4 + 3] < 16) continue;
        final dx = (x + .5) / 4 - 54;
        final dy = (y + .5) / 4 - 54;
        expect(
          dx * dx + dy * dy,
          lessThanOrEqualTo(33 * 33),
          reason: 'Logo must fit the 66dp safe circle',
        );
      }
    }
    await png(foreground, 'output/previews/android-phase-6-foreground.png');
    for (final round in [false, true]) {
      await png(
        await render(legacy(round: round), 384, 64),
        'output/previews/android-phase-6-legacy${round ? '-round' : ''}.png',
      );
    }
    for (final dark in [false, true]) {
      await png(
        await render(
          ColoredBox(
            color: dark ? const Color(0xFF13191F) : canvasColor,
            child: const Center(child: SpaceHouse(size: 153.6)),
          ),
          780,
          390,
        ),
        'output/previews/android-phase-6-splash-${dark ? 'dark' : 'light'}.png',
      );
    }
    await tester.runAsync(() async {
      await write('$res/drawable/ic_launcher_foreground.xml', vector(dp: 108));
      await write(
        '$res/drawable/ic_launcher_monochrome.xml',
        vector(dp: 108, monochrome: true),
      );
      await write('$res/drawable/splash_logo.xml', vector(dp: 288));
      for (final suffix in ['', '_round']) {
        await write(
          '$res/mipmap-anydpi-v26/ic_launcher$suffix.xml',
          adaptive(),
        );
      }
    });
  });
}
